-- ===============================================================
-- 第 1 階段安全修復的資料庫結構調整
-- 2026-08-14
-- ===============================================================
--
-- 適用對象：已經有一份運作中的 db21 資料庫，不想整個重新匯入的情況。
-- 若是全新安裝，直接匯入 db/db21.sql 即可，不需要執行本檔。
--
-- 執行方式：
--     C:\xampp\mysql\bin\mysql.exe -u root -p db21 < db\migrate_stage1.sql
-- ===============================================================

USE `db21`;

-- ---------------------------------------------------------------
-- 1. admin.pw 改為 VARCHAR(255)
-- ---------------------------------------------------------------
-- password_hash() 以 bcrypt 產生的雜湊為 60 字元，
-- 未來換用 argon2id 會更長，因此保留 255。
-- 原本是 text，雖然放得下，但無法建立索引也不利於長度檢查。
ALTER TABLE `admin`
    MODIFY `pw` VARCHAR(255) NOT NULL;

-- ---------------------------------------------------------------
-- 2. admin.acc 改為 VARCHAR(64) 並加上唯一索引
-- ---------------------------------------------------------------
-- 舊版 acc 是 text，無法建立 UNIQUE 索引，因此可以建出重複帳號 ——
-- 登入時只會比對到其中一筆，行為不可預期。
ALTER TABLE `admin`
    MODIFY `acc` VARCHAR(64) NOT NULL;

-- 若已存在重複帳號，下面這行會失敗。
-- 請先執行以下查詢找出重複資料並手動清理後再重跑：
--     SELECT acc, COUNT(*) c FROM admin GROUP BY acc HAVING c > 1;
ALTER TABLE `admin`
    ADD UNIQUE KEY `uniq_admin_acc` (`acc`);

-- ---------------------------------------------------------------
-- 3. 確認結果
-- ---------------------------------------------------------------
SHOW CREATE TABLE `admin`;

-- 檢查還有哪些帳號是明文密碼（bcrypt 雜湊固定以 $2y$ 開頭）。
-- 這些帳號會在下次登入成功時由 api/login.php 自動升級為雜湊；
-- 若希望立刻處理，請用 php db/create_admin.php 重設密碼。
SELECT `id`, `acc`,
       CASE WHEN `pw` LIKE '$2y$%' OR `pw` LIKE '$argon2%'
            THEN '已雜湊' ELSE '⚠ 仍為明文' END AS pw_status
FROM `admin`;
